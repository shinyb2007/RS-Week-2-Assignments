import numpy as np

a = np.array([1,2,3])

b = np.array([4,5,6])

print("Addition:")
print(a + b)

print("\nSubtraction:")
print(a - b)

print("\nMultiplication:")
print(a * b)

print("\nDivision:")
print(a / b)

print("\nPower of 3:")
print(a ** 3)

print("\nSquare:")
print(a ** 2)

print("\nMean:")
print(np.mean(a))